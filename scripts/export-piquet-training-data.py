#!/usr/bin/env python3
"""Write RL-environment/piquet/training-data.js for the "How the agent was trained" charts.

Reads the gym run's metrics.csv up to the published checkpoint (model/manifest.json)
and the JSON reports of `cardgym piquet evaluate --output` (one per checkpoint,
duplicate deals against the rule-based heuristic). Numpy-free.

Usage: python scripts/export-piquet-training-data.py --evals path/to/reports
"""
import argparse
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT.parent / 'card_playing_gym')
    parser.add_argument('--evals', type=Path, required=True, help='directory of evaluate --output reports')
    parser.add_argument('--bucket', type=int, default=100, help='updates per point of the self-play curves')
    args = parser.parse_args()
    manifest = json.loads((ROOT / 'RL-environment/piquet/model/manifest.json').read_text())
    run, live = manifest['run'], manifest['iteration']
    with open(args.source / 'runs/piquet' / run / 'metrics.csv') as handle:
        rows = [row for row in csv.DictReader(handle) if int(row['iteration']) <= live]

    def curve(key, scale=1.0):
        points, bucket = [], []
        for row in rows:
            bucket.append(float(row[key]))
            if int(row['iteration']) % args.bucket == 0:
                points.append([int(row['iteration']), round(scale * sum(bucket) / len(bucket), 4)])
                bucket = []
        return points

    reports = sorted((json.loads(path.read_text()) for path in args.evals.glob('*.json')), key=lambda r: r['iteration'])
    heuristic = [dict(iteration=r['iteration'], margin=round(r['model_return'], 3), stderr=round(r['stderr'], 3),
                      elder=round(r['elder_margin'], 3), younger=round(r['younger_margin'], 3), wins=round(r['win_rate'], 4),
                      deals=r['games']) for r in reports if r['opponent'] == 'heuristic']
    data = dict(
        source=dict(run=run, liveCheckpoint=live, bucket=args.bucket),
        totals=dict(hours=round(sum(float(r['iteration_sec']) for r in rows) / 3600, 2),
                    deals=int(sum(float(r['games']) for r in rows)),
                    decisions=int(sum(float(r['decisions']) for r in rows)),
                    updates=len(rows), parameters=9_078_030),
        heuristic=heuristic,
        elderMargin=curve('elder_margin'),
        pointsPerDeal=curve('points_per_deal'),
        pique=curve('pique_rate'), repique=curve('repique_rate'), capot=curve('capot_rate'),
    )
    out = ROOT / 'RL-environment/piquet/training-data.js'
    out.write_text('// Generated by scripts/export-piquet-training-data.py; do not edit by hand.\n'
                   'export const PIQUET_TRAINING_DATA = ' + json.dumps(data, separators=(',', ':')) + ';\n')
    print(f'{out.relative_to(ROOT)}: {len(rows)} updates, {len(heuristic)} evaluations')


if __name__ == '__main__':
    main()
